#!/usr/bin/env bash
# PI5-8: turn host_golden.sh output (llama.cpp ids and greedy tokens) into the pi5_measure.h the measurement
# kernel build includes. Requests: the short prompt three times (variance), then the two long prompts.
#   gen_measure_header.sh GOLDEN_DIR EOS_ID > pi5_measure.h
set -euo pipefail
d="${1:?golden dir}"; eos="${2:?eos id}"
echo "/* generated by scripts/pi5-8/gen_measure_header.sh from $d (llama.cpp reference) */"
echo "#define MEAS_EOS ${eos}u"
for p in short long1 long2; do
    ids=$(head -1 "$d/$p.ref" | cut -d' ' -f2- | tr ' ' ',')
    exp=$(awk '$1=="step"{printf "%s%su", (n++?",":""), $3}' "$d/$p.ref")
    echo "static const uint32_t meas_${p}_ids[] = {${ids}};"
    echo "static const uint32_t meas_${p}_exp[] = {${exp}};"
done
cat <<'EOT'
struct meas_req { const char *name; unsigned nids; const uint32_t *ids; unsigned nexp; const uint32_t *exp; };
#define MEAS_N(a) ((unsigned)(sizeof(a) / sizeof((a)[0])))
static const struct meas_req meas_reqs[] = {
    {"short", MEAS_N(meas_short_ids), meas_short_ids, MEAS_N(meas_short_exp), meas_short_exp},
    {"short", MEAS_N(meas_short_ids), meas_short_ids, MEAS_N(meas_short_exp), meas_short_exp},
    {"short", MEAS_N(meas_short_ids), meas_short_ids, MEAS_N(meas_short_exp), meas_short_exp},
    {"long1", MEAS_N(meas_long1_ids), meas_long1_ids, MEAS_N(meas_long1_exp), meas_long1_exp},
    {"long2", MEAS_N(meas_long2_ids), meas_long2_ids, MEAS_N(meas_long2_exp), meas_long2_exp},
};
#define MEAS_NREQ MEAS_N(meas_reqs)
EOT
